window.Lines = (() => {
  // 洗牌抽：每個人輪完整副牌才會重複（記在瀏覽器裡）
  function deck(key, n) {
    const k = 'danceIsland.deck.' + key;
    let left = [];
    try { left = JSON.parse(localStorage.getItem(k) || '[]').filter(i => i < n); } catch (e) {}
    if (!left.length) left = Array.from({ length: n }, (_, i) => i);
    const i = left.splice(Math.floor(Math.random() * left.length), 1)[0];
    try { localStorage.setItem(k, JSON.stringify(left)); } catch (e) {}
    return i;
  }
  const npc = () => { const L = LINES.npc[I18N.lang] || LINES.npc.zh; return L[deck('npc.' + I18N.lang, L.length)]; };
  // 每日小卡：同一個人同一天固定同一句；N 天內不會重複
  function quoteOf(uid, day) {
    const N = LINES.quotes.length;
    let a = 0; for (const c of String(uid)) a = (a * 31 + c.charCodeAt(0)) | 0;
    const rnd = () => { a = (a + 0x6D2B79F5) | 0; let x = Math.imul(a ^ (a >>> 15), 1 | a); x = (x + Math.imul(x ^ (x >>> 7), 61 | x)) ^ x; return ((x ^ (x >>> 14)) >>> 0) / 4294967296; };
    const perm = Array.from({ length: N }, (_, i) => i);
    for (let i = N - 1; i > 0; i--) { const j = Math.floor(rnd() * (i + 1)); [perm[i], perm[j]] = [perm[j], perm[i]]; }
    const dn = Math.floor(Date.parse(day + 'T00:00:00Z') / 864e5);
    return LINES.quotes[perm[((dn % N) + N) % N]];
  }
  return { deck, npc, quoteOf };
})();
